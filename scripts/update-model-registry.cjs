#!/usr/bin/env node
/**
 * Regenerates src/agent/model-registry.json from LiteLLM's public model registry.
 *
 * Aurix needs a context window for whatever model the operator points it at. Providers
 * often will not say — 9router's /v1/models returns only {id, object, owned_by} — so the
 * fallback is a lookup table, and a hand-maintained table goes stale the moment a new
 * model ships. LiteLLM maintains one across ~3000 models, so we borrow theirs.
 *
 * Vendored rather than fetched at runtime: no network on the hot path, deterministic
 * builds, and the diff is reviewable when it changes. Filtered to chat models that
 * declare an input window, which takes 1.6 MB down to ~112 KB.
 *
 * Run: node scripts/update-model-registry.cjs
 */
const fs = require('fs');
const path = require('path');

const SOURCE =
  'https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json';
const OUT = path.resolve(__dirname, '..', 'src', 'agent', 'model-registry.json');

async function main() {
  process.stdout.write(`fetching ${SOURCE}\n`);
  const res = await fetch(SOURCE);
  if (!res.ok) throw new Error(`fetch failed: HTTP ${res.status}`);
  const raw = await res.json();

  const models = {};
  let skipped = 0;
  for (const [id, entry] of Object.entries(raw)) {
    if (!entry || typeof entry !== 'object') continue;
    if (entry.mode !== 'chat') {
      skipped++;
      continue;
    }
    const input = Number(entry.max_input_tokens);
    if (!Number.isFinite(input) || input <= 0) {
      skipped++;
      continue;
    }
    const output = Number(entry.max_output_tokens);
    // Array rather than object: ~30% smaller across 2000+ entries.
    models[id.toLowerCase()] = Number.isFinite(output) && output > 0 ? [input, output] : [input];
  }

  const payload = {
    _source: SOURCE,
    _generated: new Date().toISOString().slice(0, 10),
    _note: 'Generated by scripts/update-model-registry.cjs. Do not edit by hand.',
    models,
  };

  fs.writeFileSync(OUT, JSON.stringify(payload));
  const kb = Math.round(fs.statSync(OUT).size / 1024);
  process.stdout.write(`wrote ${OUT}\n  ${Object.keys(models).length} chat models, ${kb} KB (skipped ${skipped})\n`);
}

main().catch((e) => {
  process.stderr.write(`update-model-registry failed: ${e.message}\n`);
  process.exit(1);
});
